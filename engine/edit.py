# ---------- looks: parametric presets at strength 1; strength k scales every parameter's distance from identity

@dataclass(frozen=True)
class Look:
    contrast: float = 1.0
    saturation: float = 1.0
    brightness: float = 0.0
    rs: float = 0.0   # colorbalance shadows / midtones / highlights, red and blue
    bs: float = 0.0
    rm: float = 0.0
    bm: float = 0.0
    rh: float = 0.0
    bh: float = 0.0


# ponytail: no curves=preset (it cannot scale with strength); lut3d is the upgrade for real film LUTs.
LOOKS = {
    "warm": Look(contrast=1.06, saturation=1.2, brightness=0.02, rs=0.10, bs=-0.10, rm=0.09, bm=-0.09, rh=0.06, bh=-0.08),
    "cool": Look(contrast=1.06, saturation=0.9, rs=-0.12, bs=0.17, rm=-0.09, bm=0.14, rh=-0.05, bh=0.10),
    "film": Look(contrast=1.2, saturation=0.78, brightness=-0.02, rs=-0.06, bs=0.10, rm=0.02, bm=-0.03, rh=0.10, bh=-0.08),
    "mono": Look(contrast=1.25, saturation=0.0, brightness=-0.02),
    "punch": Look(contrast=1.3, saturation=1.6, brightness=0.01),
}
_IDENT = Look()
# film-style 3D LUTs (33^3 .cube, generated by luts/make_luts.py); strength k is a LUT blended k of the way from identity,
# which is exactly a k mix of graded and ungraded frames (lut3d interpolation is linear in the table)
LUTS = ("teal-orange", "warm-film", "bleach", "clean-pop")
LUT_DIR = Path(__file__).parent / "luts"


def lut_file(name, k):
    """The .cube for a LUT look at strength k (rounded to 0.05): the bundled file at 1, else a blend cached in DATA/luts."""
    k = round(k * 20) / 20
    src = LUT_DIR / f"{name}.cube"
    if k >= 1:
        return src
    out = core.DATA / "luts" / f"{name}-{k:.2f}.cube"
    if not out.is_file():
        import importlib.util
        import numpy as np
        sp = importlib.util.spec_from_file_location("make_luts", LUT_DIR / "make_luts.py")
        mk = importlib.util.module_from_spec(sp)
        sp.loader.exec_module(mk)
        tab = np.array([[float(v) for v in ln.split()] for ln in src.read_text().splitlines() if ln[:1].isdigit()])
        ident = mk.grid()
        out.parent.mkdir(parents=True, exist_ok=True)
        tmp = out.with_suffix(f".{os.getpid()}.tmp")
        mk.write(tmp, ident + (tab - ident) * k, f"{name} {k:.2f}")
        tmp.replace(out)
    return out


def _num(x):
    return format(round(x, 3) + 0.0, "g")  # +0.0 turns -0.0 into 0.0


def look_filters(look):
    """(name, strength) -> ffmpeg filter text, '' for none or identity. Numbers and our own LUT paths only, safe to inline."""
    if not look or not look[0]:
        return ""
    name, k = look
    if name in LUTS:
        if round(k * 20) == 0:
            return ""
        f = str(lut_file(name, k))
        if any(ch in f for ch in "'\\\n"):  # it goes inside a quoted filter argument
            raise RuntimeError(f"LUT path cannot be used by ffmpeg: {f}")
        return f"lut3d=file='{f}':interp=tetrahedral"
    p = LOOKS[name]
    v = {f.name: getattr(_IDENT, f.name) + (getattr(p, f.name) - getattr(_IDENT, f.name)) * k for f in fields(Look)}
    parts = []
    for flt, keys in (("eq", ("contrast", "saturation", "brightness")), ("colorbalance", ("rs", "bs", "rm", "bm", "rh", "bh"))):
        args = [f"{x}={_num(v[x])}" for x in keys if _num(v[x]) != _num(getattr(_IDENT, x))]
        if args:
            parts.append(f"{flt}=" + ":".join(args))
    return ",".join(parts)


# ---------- spec

def default_spec():
    return {"version": 1, "format": {"aspect": "16:9", "size": 1080, "fps": 30, "fade_in": 0.0, "fade_out": 0.0}, "audio": [], "clip_volume": 1.0, "duck": True,
            "look": {"name": None, "strength": 1.0}, "clips": {}, "transitions": {},
            "captions": dict(CAPTIONS_DEFAULT), "sync": dict(SYNC_DEFAULT), "sfx": {}, "texts": []}


def output_size(aspect, size, preview):
    """(width, height), both even. Preview short side is at most 540."""
    if aspect not in ASPECTS:
        raise ValueError(f"aspect must be one of {list(ASPECTS)}")
    short = min(size, 540) if preview else size
    w, h = ASPECTS[aspect]
    even = lambda x: 2 * round(x / 2)  # noqa: E731
    return (even(short * w / h), short) if w >= h else (short, even(short * h / w))


def conn():
    c = core.connect()
    c.execute(EDIT_SCHEMA)
    return closing(c)


def _prune(spec, col):
    ids = {str(i["item_id"]) for i in col["items"]}
    for k in ("clips", "transitions", "sfx"):
        spec[k] = {i: v for i, v in spec[k].items() if i in ids}


def _fill(spec):
    """Specs saved before fades / audio existed gain the defaults."""
    for k, v in (("fade_in", 0.0), ("fade_out", 0.0)):
        spec["format"].setdefault(k, v)
    for k, v in (("audio", []), ("clip_volume", 1.0), ("duck", True), ("sfx", {}), ("texts", [])):
        spec.setdefault(k, v)
    spec["sync"] = {**SYNC_DEFAULT, **spec.get("sync", {})}


def _read(c, col):
    row = c.execute("select spec, rev from edit_specs where collection_id = ?", (col["id"],)).fetchone()
    spec, rev = (json.loads(row[0]), row[1]) if row else (default_spec(), 0)
    _fill(spec)
    spec["captions"] = {**CAPTIONS_DEFAULT, **spec.get("captions", {})}  # specs saved before the style options
    _prune(spec, col)
    return spec, rev


def _require_project(col):
    if col["kind"] != "project":
        raise HTTPException(422, "only projects have an edit")


def load(cid):
    """(spec with orphans pruned, rev). No row means the default spec."""
    col = library.get_collection(cid)
    _require_project(col)
    with conn() as c:
        return _read(c, col)


def mutate(cid, fn, with_conn=False):
    """Atomic read-modify-write. fn(spec, collection) edits spec in place and returns a list of clamp notes
    ({"field", "from", "to"}); it may raise HTTPException(422), which rolls everything back.
    with_conn: fn(spec, collection, c) also gets the write connection, so it can change collection items in the same
    transaction (never use library.conn() inside fn, it would wait on this lock). If fn adds items it must add them
    to collection["items"] too, or the spec entries it writes for them are pruned."""
    with conn() as c:
        c.execute("begin immediate")  # writers queue here, so parallel tool calls cannot lose updates
        try:
            col = library.get_collection(cid)
            _require_project(col)
            spec, rev = _read(c, col)
            notes = (fn(spec, col, c) if with_conn else fn(spec, col)) or []
            _prune(spec, col)
            text = json.dumps(spec, separators=(",", ":"))
            if len(text) > MAX_SPEC_BYTES:
                raise HTTPException(422, f"edit is too large ({len(text)} bytes, limit {MAX_SPEC_BYTES})")
            c.execute("insert or replace into edit_specs(collection_id, spec, rev, updated) values (?,?,?,?)",
                      (cid, text, rev + 1, time.time()))
            library.touch(c, cid)
            c.commit()
        except BaseException:
            c.rollback()
            raise
    return {"spec": spec, "rev": rev + 1, "clamped": notes}


def _clamp(notes, field, v, lo, hi):
    if math.isnan(v):
        raise HTTPException(422, f"{field} must be a number")
    nv = min(max(v, lo), hi)
    if nv != v:
        notes.append({"field": field, "from": v, "to": nv})
    return nv


# ---------- timeline (pure)

def ramp_factor(name):
    """Average speed multiplier of a ramp preset: source seconds used per output second (1 for none)."""
    return sum(f * k for f, k in RAMPS[name]) if name else 1.0


def _grid_frames(grid, fps, lead):
    """Grid seconds -> strictly increasing output frames, each cut `lead` frames early; frame 0 is always a boundary."""
    out = [0]
    for t in grid:
        f = round(t * fps) - lead
        if f > out[-1]:
            out.append(f)
    return out


def compute_timeline(items, spec, grid=None):
    """grid: output-time seconds of the beat grid (beats.grid) when spec["sync"]["track"] is set and its music was analysed.
    With a grid every cut lands on a grid point (absolute frames, so nothing drifts); without one, clip lengths come from
    their in / out points as before."""
    fps = spec["format"]["fps"]
    sync = spec.get("sync") or SYNC_DEFAULT
    G = _grid_frames(grid, fps, sync["lead"]) if grid and sync["track"] else None
    warnings, raw = [], []
    for it in items:
        e = spec["clips"].get(str(it["item_id"]), {})
        photo = it["kind"] == "image"
        t0 = it["t0"] or 0.0
        ramp = None if photo else e.get("ramp")
        if photo:
            speed, a, b = 1.0, 0.0, (it["t1"] - t0 if it["t1"] is not None else STILL_SECONDS)
        else:
            speed = e.get("speed", 1.0)
            a = t0
            b = it["t1"] if it["t1"] is not None else (it["duration"] or STILL_SECONDS)
        rate = speed * ramp_factor(ramp)  # source seconds per output second
        n = max(1, round((b - a) / rate * fps))
        adj, rf = e.get("adjust", {}), e.get("reframe", {})
        pos, pf, pt = rf.get("pos", .5), rf.get("pos_from", .5), rf.get("pos_to", .5)
        reframe = {"center": ("center", .5, .5), "manual": ("manual", pos, pos),
                   "pan": ("pan", pf, pt)}[rf.get("mode", "center")]
        lk = e["look"] if "look" in e else spec["look"]
        mo = e.get("motion", "none")
        raw.append(dict(item_id=it["item_id"], uuid=it["uuid"], kind="photo" if photo else "video",
                        src_in=a, src_out=b, speed=speed, volume=0.0 if (e.get("mute") or ramp) else e.get("volume", 1.0),
                        adjust=(adj.get("exposure", 0.0), adj.get("contrast", 1.0), adj.get("saturation", 1.0),
                                adj.get("warmth", 0.0)),
                        look=(lk["name"], lk.get("strength", 1.0)) if lk["name"] else None,
                        reframe=reframe, frames=n,
                        motion=(mo, e.get("motion_amount", MOTION_AMOUNT)) if mo != "none" else None,
                        flash=bool(e.get("flash")), shake=bool(e.get("shake")), ramp=ramp))
        raw[-1]["_rate"], raw[-1]["_avail"] = rate, (None if photo else (it["duration"] or b))
        raw[-1]["_beats"], raw[-1]["_hit"] = e.get("beats"), (None if photo else e.get("hit"))
    if raw and spec["transitions"].get(str(raw[-1]["item_id"]), {"type": "cut"})["type"] != "cut":
        warnings.append("the transition after the last clip does nothing (there is no next clip)")
    bounds = None
    if G:  # cut frames on the grid: clip k covers grid points g_k .. g_k + beats_k
        unit = (G[-1] - G[0]) / max(len(G) - 1, 1)
        g, bounds = 0, [0]
        for r in raw:
            k = r["_beats"] or max(1, round(r["frames"] / unit))
            if g + k >= len(G):
                warnings.append("the edit runs past the beat grid; the last clips keep their own length")
                bounds = None
                break
            g += k
            bounds.append(G[g])
        if bounds:
            for r, x, y in zip(raw, bounds, bounds[1:]):
                r["frames"] = y - x
    tf = [0] * len(raw)  # transition frames after each clip
    for i in range(len(raw) - 1):
        t = spec["transitions"].get(str(raw[i]["item_id"]))
        if not t or t["type"] == "cut":
            continue
        want = round(t["duration"] * fps)
        got = min(want, raw[i]["frames"] // 2, raw[i + 1]["frames"] // 2, raw[i]["frames"] - (tf[i - 1] if i else 0))
        if got < MIN_TRANS_FRAMES:
            warnings.append(f"transition after clip {i + 1} is too short for its neighbours and became a cut")
            got = 0
        elif got < want:
            warnings.append(f"transition after clip {i + 1} shortened from {want} to {got} frames "
                            "(at most half of each neighbouring clip)")
        tf[i] = got
    if bounds:  # each overlap is centred on its beat: start_k = bound_k - tf/2, so clips grow by the overlaps they own
        starts = [0] + [bounds[i + 1] - tf[i] // 2 for i in range(len(raw) - 1)]
        ends = [starts[i + 1] + tf[i] for i in range(len(raw) - 1)] + [bounds[len(raw)]]
        for i, r in enumerate(raw):
            r["frames"] = ends[i] - starts[i]
    segs, start = [], 0
    for i, r in enumerate(raw):
        n = r["frames"]
        if r["kind"] == "video" and (bounds or r["_hit"] is not None):
            r["src_in"], r["src_out"], note = _fit_source(r, n, fps, start, bounds and bounds[i], G)
            if note:
                warnings.append(f"clip {i + 1} {note}")
        if n / fps < SHORT_CLIP:
            warnings.append(f"clip {i + 1} is only {n / fps:.2f}s long")
        beat_frames = tuple(f - start for f in (G or ()) if start < f < start + n)
        t = spec["transitions"].get(str(r["item_id"]))
        seg = {k: v for k, v in r.items() if not k.startswith("_")}
        segs.append(Seg(start_frame=start, trans_after=(XFADE[t["type"]], tf[i]) if tf[i] else None,
                        beat_frames=beat_frames, **seg))
        start += n - tf[i]
    total = segs[-1].start_frame + segs[-1].frames if segs else 0
    sfx = tuple(sorted((segs[i + 1].start_frame + (segs[i].trans_after[1] // 2 if segs[i].trans_after else 0), name)
                       for i, s in enumerate(segs[:-1]) for name in [spec.get("sfx", {}).get(str(s.item_id))] if name))
    texts = []
    for t in spec.get("texts", ()):  # start snaps to the nearest grid point when synced; the spec keeps it as entered
        f0 = round(t["start"] * fps)
        if G:
            f0 = min(G, key=lambda g: abs(g - f0))
        n = min(round(t["dur"] * fps), total - f0)
        if n < round(0.3 * fps):
            warnings.append(f"text {t['id']!r} starts after the edit ends and is not shown")
            continue
        texts.append({**titles.DEFAULT, **t, "start_frame": f0, "frames": n})
    ident = json.dumps([spec, [(i["item_id"], i["uuid"], i["t0"], i["t1"], i["pos"]) for i in items], G],
                       sort_keys=True, separators=(",", ":"))
    return Timeline(fps=fps, aspect=spec["format"]["aspect"], size=spec["format"]["size"], segs=tuple(segs),
                    total_frames=total, warnings=tuple(warnings), edit_hash=hashlib.sha1(ident.encode()).hexdigest(),
                    fade_in=spec["format"].get("fade_in", 0.0), fade_out=spec["format"].get("fade_out", 0.0),
                    audio=tuple(spec.get("audio", ())), clip_volume=spec.get("clip_volume", 1.0), duck=spec.get("duck", True),
                    sfx=sfx, texts=tuple(texts))


def _fit_source(r, n, fps, start, bound, G):
    """(src_in, src_out, warning or None) for a video clip that must fill n output frames. A hit (source seconds) slides
    the in point so the hit lands on the grid point nearest to where it would fall (or stays put without a grid).
    ponytail: hit placement ignores ramps (it assumes a constant rate)."""
    rate, avail = r["_rate"], r["_avail"]
    need = n / fps * rate
    a, note = r["src_in"], None
    if r["_hit"] is not None:
        h = r["_hit"]
        at = (h - a) / rate * fps  # frames from clip start where the hit falls now
        pts = [f - start for f in (G or ()) if start <= f <= start + n]
        if bound is not None:
            pts.append(bound - start)
        if pts:
            p = min(pts, key=lambda p: abs(p - at))
            a = h - p / fps * rate
        a = min(max(a, 0.0), max(avail - need, 0.0))
    b = a + need
    if b > avail + 1e-6:
        note = f"needs {need:.2f}s of source but only {avail - a:.2f}s is there; its last frame holds"
        b = avail
    return a, b, note


def grid_for(spec):
    """(output-time beat grid in seconds, or None; warning or None) for the spec's sync track. Analyses the music on first use
    (a few seconds, cached by file)."""
    sid = (spec.get("sync") or {}).get("track")
    if not sid:
        return None, None
    t = next((t for t in spec.get("audio", ()) if t["id"] == sid), None)
    if not t:
        return None, f"beat sync is on but audio track {sid!r} is gone; cuts are not synced"
    import beats
    try:
        return beats.grid(t, beats.analyze(t["path"]), spec["sync"]["grid"], MAX_SECONDS), None
    except (RuntimeError, OSError, ValueError, subprocess.SubprocessError) as e:
        return None, f"could not find the beat of {Path(t['path']).name} ({str(e)[:120]}); cuts are not synced"


def timeline_for(items, spec):
    g, why = grid_for(spec)
    tl = compute_timeline(items, spec, g)
    if why:
        from dataclasses import replace
        tl = replace(tl, warnings=(why, *tl.warnings))
    return tl, g


def snapshot(cid):
    """(Timeline, Spec) from one read; later edits do not affect a running render."""
    col = library.get_collection(cid)
    _require_project(col)
    with conn() as c:
        spec, _ = _read(c, col)
    return timeline_for(col["items"], spec)[0], spec


