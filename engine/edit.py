@router.patch("/collections/{cid}/edit")
def patch_edit(cid: int, body: EditPatch):
    given, flipped = body.model_fields_set, []
    picks = None
    if body.sync_track not in (None, "none") and "sync_track" in given:  # find the beat before the write lock
        spec0, _ = load(cid)
        t = next((t for t in spec0["audio"] if t["id"] == body.sync_track), None)
        if not t:
            raise HTTPException(422, f"no audio track {body.sync_track!r}; add the music first (ids: {[t['id'] for t in spec0['audio']]})")
        import beats
        try:
            beats.analyze(t["path"])
        except (RuntimeError, OSError, subprocess.SubprocessError) as e:
            raise HTTPException(422, f"could not find the beat of {Path(t['path']).name}: {str(e)[:200]}")
    if body.captions and "captions" in given:  # speech guesses read audio files: do them before the write lock
        import captions
        spec0, _ = load(cid)
        if not spec0["captions"]["on"] and not any(e.get("captions") for e in spec0["clips"].values()):
            picks = {i["item_id"] for i in library.get_collection(cid)["items"]
                     if i["kind"] != "image" and captions.likely_speech(i["uuid"])}

    def fn(spec, col):
        notes = []
        for k in ("aspect", "size", "fps"):
            if k in given:
                spec["format"][k] = getattr(body, k)
        if "look" in given:
            _set_look(spec, "look", body.look)
        if "look_strength" in given:
            spec["look"]["strength"] = _clamp(notes, "look_strength", body.look_strength, 0, 1)
        for k in ("fade_in", "fade_out"):
            if k in given:
                spec["format"][k] = _clamp(notes, k, getattr(body, k), 0, MAX_FADE)
        if "clip_volume" in given:
            spec["clip_volume"] = _clamp(notes, "clip_volume", body.clip_volume, 0, 1)
        if "duck" in given:
            spec["duck"] = body.duck
        if "sync_track" in given:
            tid = None if body.sync_track in (None, "none") else body.sync_track
            if tid and not any(t["id"] == tid for t in spec["audio"]):
                raise HTTPException(422, f"no audio track {tid!r}")
            spec["sync"]["track"] = tid
        for k in ("grid", "lead"):
            if f"sync_{k}" in given:
                spec["sync"][k] = getattr(body, f"sync_{k}")
        if "captions" in given:
            flipped.append(body.captions and not spec["captions"]["on"])
            spec["captions"]["on"] = body.captions
            if picks and not any(e.get("captions") for e in spec["clips"].values()):
                for i in picks:
                    spec["clips"].setdefault(str(i), {})["captions"] = True
        for k in ("style", "position", "font", "size", "color", "highlight_color", "highlight", "uppercase", "max_words"):
            if f"caption_{k}" in given:
                spec["captions"][k] = getattr(body, f"caption_{k}")
        if body.caption_clips is not None and "caption_clips" in given:
            ids = {str(i["item_id"]): i["kind"] for i in col["items"]}
            bad = [i for i in body.caption_clips if str(i) not in ids or ids[str(i)] == "image"]
            if bad:
                raise HTTPException(422, f"caption_clips must be video clips of this project; not: {bad}")
            want = {str(i) for i in body.caption_clips}
            for k in ids:
                e = spec["clips"].setdefault(k, {})
                if k in want:
                    e["captions"] = True
                else:
                    e.pop("captions", None)
                if not e:
                    del spec["clips"][k]
        return notes

    out = mutate(cid, fn)
    # lazy import; the edit is already saved if this raises. Starts for newly selected clips or word timing too.
    if out["spec"]["captions"]["on"] and (flipped and flipped[0] or given & {"caption_clips", "caption_highlight", "caption_style"}):
        import captions
        captions.start_transcription(cid)
    return out


@router.patch("/collections/{cid}/edit/clips/{item_id}")
def patch_clip(cid: int, item_id: int, body: ClipPatch):
    given = body.model_fields_set

    def fn(spec, col):
        item = next((i for i in col["items"] if i["item_id"] == item_id), None)
        if not item:
            raise HTTPException(404, "no such item")
        if item["kind"] == "image" and body.speed not in (None, 1.0):
            raise HTTPException(422, "photos cannot change speed")
        if item["kind"] == "image" and body.captions:
            raise HTTPException(422, "photos have no speech to caption")
        if item["kind"] == "image" and body.ramp not in (None, "none"):
            raise HTTPException(422, "photos cannot ramp speed; use motion instead")
        if item["kind"] == "image" and body.hit is not None and body.hit >= 0:
            raise HTTPException(422, "photos have no moment to land on a beat")
        notes, e = [], spec["clips"].setdefault(str(item_id), {})
        for k in given & CLIP_FIELDS.keys():
            (*parents, leaf), default, lo, hi = CLIP_FIELDS[k]
            d = e
            for p in parents:
                d = d.setdefault(p, {})
            v = getattr(body, k)
            if v is not None and lo is not None:
                v = _clamp(notes, k, v, lo, hi)
            if v is None or v == default:
                d.pop(leaf, None)
            else:
                d[leaf] = v
        if "look" in given:
            if body.look is None:
                e.pop("look", None)
            else:
                _set_look(e, "look", body.look)
        if "look_strength" in given:
            if body.look_strength is None:
                if "look" in e:
                    e["look"]["strength"] = 1.0
            else:
                if "look" not in e:  # strength alone adjusts the project look for this clip
                    if not spec["look"]["name"]:
                        raise HTTPException(422, "pick a look first; there is no project look to adjust")
                    _set_look(e, "look", spec["look"]["name"])
                e["look"]["strength"] = _clamp(notes, "look_strength", body.look_strength, 0, 1)
        if "hit" in given:
            if body.hit is None or body.hit < 0:
                e.pop("hit", None)
            else:
                dur = item["duration"] or 0
                if dur and body.hit > dur:
                    raise HTTPException(422, f"hit must be within the source (0 to {dur:.2f}s)")
                e["hit"] = round(body.hit, 3)
        if body.shake:
            n = sum(1 for k, v in spec["clips"].items() if v.get("shake"))
            if n > max(1, len(col["items"]) // 2):
                raise HTTPException(422, "shake on more than half the clips looks cheap; keep it for the peaks")
        for p in ("adjust", "reframe"):
            if not e.get(p):
                e.pop(p, None)
        if not e:
            del spec["clips"][str(item_id)]
        return notes

    out = mutate(cid, fn)
    if body.captions and out["spec"]["captions"]["on"]:
        import captions
        captions.start_transcription(cid)
    return out


